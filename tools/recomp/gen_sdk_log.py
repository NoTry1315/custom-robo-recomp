#!/usr/bin/env python3
"""Generate runtime/sdk_log.c: a logging override for every SDK function named
in docs/sdk_functions.md that runtime/ does not implement by hand.

    PYTHONUTF8=1 python tools/recomp/gen_sdk_log.py

Run it again whenever a hand-written sdk_* function is added to runtime/.
Names follow recomp.py: the lower address of a duplicate name keeps the plain
name, later ones get an _XXXXXXXX suffix. Functions not in the doc
(sdk_*_unlisted_*) keep their weak logging stub in gen/sdk_stubs.c."""
import re
from pathlib import Path
from recomp import ROOT, load_sdk_doc, STUB_MODULES

RUNTIME = ROOT / 'runtime'
OUT = RUNTIME / 'sdk_log.c'


def main():
    ranges, names = load_sdk_doc()

    def module(a):
        for lo, hi, m in ranges:
            if lo <= a < hi:
                return m
        return None

    hand = set()
    for f in RUNTIME.glob('*.c'):
        if f != OUT:
            hand |= set(re.findall(r'^void (sdk_\w+)\(void\)', f.read_text(encoding='utf-8'), re.M))
    seen, out = set(), []
    for a in sorted(names):
        if module(a) not in STUB_MODULES:
            continue
        n = 'sdk_' + re.sub(r'\W', '_', names[a])
        if n in seen:
            n += f'_{a:08x}'
        seen.add(n)
        if n not in hand:
            out.append(f'void {n}(void) {{ recomp_sdk_call("{n[4:]}"); }}')
    hdr = ['/* generated by tools/recomp/gen_sdk_log.py from docs/sdk_functions.md -- do not edit */',
           '/* Logging overrides for SDK functions not implemented by hand in runtime/. */',
           '#include "ppc.h"', '']
    OUT.write_text('\n'.join(hdr + out) + '\n', encoding='utf-8')
    print(f'{len(out)} logging overrides, {len(hand)} hand-written, {len(seen)} doc names')


if __name__ == '__main__':
    main()
