"""Writes runtime/vsh/*.v.pica: vertex shader variants of runtime/vshader.v.pica.

Each variant does only the work of one path: lit or unlit, and n texture units
(0..3), all affine (s, t = row0/row1 . src: GX 2x4 texgen or identity, q = 1) or
all projective (divided by row2 . src, as the single shader). picasso links them
with vshader.v.pica into one SHBIN (Makefile): one DVLE each, shared code, so a
program switch does not resend the shader code. Every variant reaches the
single shader's uniforms at the same registers (u[], see sub_uniforms; runtime/gx.c checks).

Variant index (runtime/gx.c vsh_variant): lit * 7 + t, t = 0 (no texture),
1..3 (n affine units), 4..6 (n projective units). Run after changing this file:
  python tools/gen_vsh.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "runtime", "vsh")

# picasso 2.7.2 allocates uniform and constant registers across all linked files (and fails or
# segfaults past 96) while names stay per file, so a variant declares none: it reads the single
# shader's registers directly, u = c0 (uniforms in declaration order from c0, rewritten to offsets
# by sub_uniforms), k = the single shader's constant (c95: picasso allocates constants from the top) and the light loop count i0. runtime/gx.c
# checks these registers and keeps k loaded.
UNIF = [("clipm", 4), ("posm", 30), ("nrmm", 30), ("texm", 9), ("amb", 1), ("lcfg", 1), ("lights", 15)]
OFF = {}
_o = 0
for _n, _c in UNIF:
    OFF[_n] = _o
    _o += _c
NUNIF = _o

HEADER = """; generated by tools/gen_vsh.py (variant of runtime/vshader.v.pica): do not edit
.alias u c0
.alias k c95

.alias inpos v0
.alias inmat v1
.alias innrm v2
.alias intc0 v3
.alias intc1 v4
.alias intc2 v5
"""


def sub_uniforms(src):
    """clipm[i] -> u[i + 0], posm[a0.x + 1] -> u[a0.x + 5], amb -> u[73], ..."""
    def arr(m):
        idx = m.group(2).strip()
        base = OFF[m.group(1)]
        mm = re.fullmatch(r"(\w+(?:\.\w)?)(?:\s*\+\s*(\d+))?", idx)
        if mm and not mm.group(1).isdigit():
            return "u[%s + %d]" % (mm.group(1), base + int(mm.group(2) or 0))
        return "u[%d]" % (base + int(idx))
    src = re.sub(r"\b(clipm|posm|nrmm|texm|lights)\[([^\]]*)\]", arr, src)
    return re.sub(r"\b(amb|lcfg)\b(?!\[)", lambda m: "u[%d]" % OFF[m.group(1)], src)


# shared procedures (defined once, in variant 0's file; picasso procs are global)
PROCS = """
; r4 += sum(diffuse * attenuation * colour) for normal innrm at eye position r1 (a0.x = matrix row)
.proc vsh_lights
	dp3 r2.x, nrmm[a0.x], innrm
	dp3 r2.y, nrmm[a0.x + 1], innrm
	dp3 r2.z, nrmm[a0.x + 2], innrm
	dp3 r3.x, r2, r2
	rsq r3.x, r3.x
	mul r2.xyz, r2, r3.xxxx
	for i0
		add r5.xyz, lights[aL], -r1
		dp3 r6.x, r5, r5
		rsq r6.y, r6.x
		mul r5.xyz, r5, r6.yyyy
		rcp r6.z, r6.y
		dp3 r7.x, r5, r2
		mul r7.x, lcfg.xxxx, r7.x
		add r7.x, lcfg.yyyy, r7.x
		max r7.x, lcfg.zzzz, r7.x
		dp3 r7.y, lights[aL + 1], -r5
		mov r8.x, k.y
		mov r8.y, r7.y
		mul r8.z, r7.y, r7.y
		dp3 r7.z, lights[aL + 2], r8
		max r7.z, k.x, r7.z
		mov r8.y, r6.z
		mul r8.z, r6.z, r6.z
		dp3 r7.w, lights[aL + 3], r8
		rcp r7.w, r7.w
		mul r7.z, r7.z, r7.w
		mul r7.x, r7.x, r7.z
		mul r9, lights[aL + 4], r7.xxxx
		add r4, r4, r9
	.end
.end
"""


def variant(lit, n, proj):
    name = "vsh_l%d_t%d%s" % (lit, n, "p" if proj else "")
    o = [HEADER, ".out outpos position", ".out outclr color"]
    o += [".out outtc%d texcoord%d" % (u, u) for u in range(n)]
    o += ["", ".entry " + name, ".proc " + name,
          "\t; dph = dp4 with the left operand's w = 1",
          "\tmova a0.x, inpos.w",
          "\tdph r1.x, inpos, posm[a0.x]",
          "\tdph r1.y, inpos, posm[a0.x + 1]",
          "\tdph r1.z, inpos, posm[a0.x + 2]"]
    o += ["\tdph outpos.%s, r1, clipm[%d]" % ("xyzw"[i], i) for i in range(4)]
    if lit:
        o += ["\tmov r4, amb", "\tcall vsh_lights", "\tmax r4, k.xxxx, r4", "\tmin r4, k.yyyy, r4",
              "\tmul r9, k.zzzz, inmat", "\tmul outclr, r9, r4"]
    else:   # amb is in [0, 1] (gx.c set_lighting_inner): the clamp is the identity
        o += ["\tmul r9, k.zzzz, inmat", "\tmul outclr, amb, r9"]
    for u in range(n):
        if proj:
            o += ["\tdp4 r10.x, texm[%d], intc%d" % (3 * u, u),
                  "\tdp4 r10.y, texm[%d], intc%d" % (3 * u + 1, u),
                  "\tdp4 r10.z, texm[%d], intc%d" % (3 * u + 2, u),
                  "\trcp r10.z, r10.z",
                  "\tmul outtc%d, r10.zzzz, r10" % u]
        else:
            o += ["\tdp4 outtc%d.x, texm[%d], intc%d" % (u, 3 * u, u),
                  "\tdp4 outtc%d.y, texm[%d], intc%d" % (u, 3 * u + 1, u)]
    o += ["\tend", ".end"]
    return name, sub_uniforms("\n".join(o) + "\n")


def main():
    os.makedirs(OUT, exist_ok=True)
    i = 0
    for lit in (0, 1):
        for t in range(7):
            n, proj = (t, 0) if t < 4 else (t - 3, 1)
            name, src = variant(lit, n, proj)
            if i == 0:
                src += sub_uniforms(PROCS)
            path = os.path.join(OUT, "%02d_%s.v.pica" % (i, name))
            with open(path, "w", encoding="ascii", newline="\n") as f:
                f.write(src)
            i += 1
    print("wrote %d variants to %s" % (i, os.path.normpath(OUT)))


if __name__ == "__main__":
    main()
